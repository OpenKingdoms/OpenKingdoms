/* A release build carries an FFmpeg with the Bink decoder and nothing
 * else, so terrain has to decode without asking FFmpeg for a codec. */
TEST(terrain_decodes_without_a_codec_from_ffmpeg) {
    ASSERT_EQ_INT(0, JPG_UsesFFmpeg());
    decode_chunk_and_assert("terrain/000a9eb4.jpg");
}

