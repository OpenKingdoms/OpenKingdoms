/* A release build has to decode a JPEG on its own. This one needs no
 * archive, so the release job runs it on every platform before it
 * packages anything. */
TEST(a_jpeg_decodes_with_no_game_data_at_all) {
    uint32_t *px = NULL;
    int w = 0, h = 0;
    ASSERT_EQ_INT(0, JPG_DecodeRGBA(k_probe_jpg, sizeof k_probe_jpg,
                                    &px, &w, &h));
    ASSERT_EQ_INT(32, w);
    ASSERT_EQ_INT(32, h);
    ASSERT(px != NULL);
    for (int i = 0; i < 32 * 32; i++) ASSERT_EQ_INT(0xFF, (int)(px[i] >> 24));
    /* Quadrant centres: red, green, blue, white, within a few counts. */
    static const int cx[4] = { 8, 24, 8, 24 }, cy[4] = { 8, 8, 24, 24 };
    static const int want[4][3] = {
        { 220, 30, 30 }, { 30, 200, 40 }, { 40, 60, 220 }, { 250, 250, 250 } };
    for (int q = 0; q < 4; q++) {
        uint32_t p = px[cy[q] * 32 + cx[q]];
        int r = (int)(p & 0xFF), g = (int)((p >> 8) & 0xFF), b = (int)((p >> 16) & 0xFF);
        int dr = r - want[q][0], dg = g - want[q][1], db = b - want[q][2];
        if (dr < 0) dr = -dr;
        if (dg < 0) dg = -dg;
        if (db < 0) db = -db;
        if (dr > 12 || dg > 12 || db > 12)
            printf("[q%d got %d,%d,%d want %d,%d,%d] ", q, r, g, b,
                   want[q][0], want[q][1], want[q][2]);
        ASSERT(dr <= 12 && dg <= 12 && db <= 12);
    }
    tak_free(px);
}

#ifdef TAK_HAVE_FFMPEG
#include <libavcodec/avcodec.h>
#include <libavformat/avformat.h>
#include <libswscale/swscale.h>

/* The Bink player asks FFmpeg for exactly these. A release FFmpeg is
 * built with almost everything off, so this is the contract between
 * that configure line and bink_player.c. */
TEST(the_ffmpeg_we_link_carries_what_bink_needs) {
    ASSERT(avcodec_find_decoder(AV_CODEC_ID_BINKVIDEO) != NULL);
    ASSERT(av_find_input_format("bink") != NULL);
    int have_file = 0;
    void *it = NULL;
    const char *name;
    while ((name = avio_enum_protocols(&it, 0)) != NULL)
        if (strcmp(name, "file") == 0) have_file = 1;
    ASSERT_EQ_INT(1, have_file);
    struct SwsContext *sws = sws_getContext(64, 64, AV_PIX_FMT_YUV420P,
                                            64, 64, AV_PIX_FMT_RGBA,
                                            SWS_BILINEAR, NULL, NULL, NULL);
    ASSERT(sws != NULL);
    if (sws) sws_freeContext(sws);
}
#endif

int main(int argc, char *argv[]) {
    /* --no-data: only what runs with no game files, for the release
     * job, which has none. */
    int no_data = (argc > 1 && strcmp(argv[1], "--no-data") == 0);

    TEST_SUITE("JPG_DecodeRGBA, data free");
    RUN(a_jpeg_decodes_with_no_game_data_at_all);
#ifdef TAK_HAVE_FFMPEG
    RUN(the_ffmpeg_we_link_carries_what_bink_needs);
#endif
    RUN(decode_rejects_null_input);
    RUN(decode_rejects_garbage_bytes);
    if (no_data) {
        tak_mem_shutdown();
        TEST_REPORT();
    }

    TEST_SUITE("JPG_DecodeRGBA (M5)");
    RUN(decode_chunk_000a9eb4);
    RUN(decode_chunk_001000d8);
    RUN(decode_chunk_00203818);
    RUN(decode_chunk_002c5a76);
    RUN(decode_chunk_00604e2e);

    RUN(terrain_decodes_without_a_codec_from_ffmpeg);

    if (g_vfs_ready) VFS_Shutdown();
    tak_mem_shutdown();

    TEST_REPORT();
}
